"""Writes the part configs: node positions come from the built models, everything else from this file.
usage: make_cfg.py <build/mu> <out dir>"""
import json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
MU, OUT = sys.argv[1:3]
MFR = 'Interplanetary Transport Works'
TPU = 1.875 * 0.00042561 + 0.625 * 0.005        # tonnes per unit of B9 volume
RENAME = {'top': 'node_stack_top', 'bottom': 'node_stack_bottom', 'attach': 'node_attach'}
f5 = lambda v: ('%.5f' % v).rstrip('0').rstrip('.') if abs(v) > 5e-6 else '0'


def block(name, *lines):
    return [name, '{'] + ['\t' + l for x in lines for l in (x if isinstance(x, list) else [x])] + ['}']


def mod(name, *lines):
    return block('MODULE', 'name = ' + name, *lines)


def nodes(part):
    j = json.load(open(os.path.join(MU, part + '.json')))
    out = []
    for k, n in j['nodes'].items():
        nm = RENAME.get(k, 'node_stack_' + k)
        out.append(f"{nm} = {', '.join(f5(v) for v in n['pos'])}, {', '.join(f5(v) for v in n['dir'])}, {n['size']}")
    return out


def res(name, amt, mx=None):
    return block('RESOURCE', f'name = {name}', f'amount = {amt}', f'maxAmount = {amt if mx is None else mx}')


def tank(tonnes):
    return mod('ModuleB9PartSwitch', 'moduleID = ITS_Fuel', 'switcherDescription = Propellant', 'baseVolume = %d' % round(tonnes / TPU),
               block('SUBTYPE', 'name = Methalox', 'title = Methalox', 'tankType = ITSLMOX', 'primaryColor = #8fb7d9', 'secondaryColor = #e8e8e8'),
               block('SUBTYPE', 'name = Dry', 'title = Dry', 'primaryColor = #555555', 'secondaryColor = #888888'))


def rcs(power, effects=True):
    return mod('ModuleRCSFX', 'thrusterTransformName = RCSthruster', f'thrusterPower = {power}', 'resourceFlowMode = STAGE_PRIORITY_FLOW',
               'runningEffectName = running', 'stagingEnabled = False',
               block('PROPELLANT', 'name = LqdMethane', 'ratio = 3', 'DrawGauge = True'), block('PROPELLANT', 'name = Oxidizer', 'ratio = 1'),
               block('atmosphereCurve', 'key = 0 310', 'key = 1 210', 'key = 4 0.001'))


RCS_FX = block('EFFECTS', block('running',
               block('AUDIO_MULTI_POOL', 'channel = Ship', 'transformName = RCSthruster', 'clip = sound_rocket_mini', 'volume = 0.0 0.0', 'volume = 0.1 0.0',
                     'volume = 0.5 0.06', 'volume = 1.0 0.15', 'pitch = 0.0 0.8', 'pitch = 1.0 1.1', 'loop = true'),
               block('MODEL_MULTI_PARTICLE', 'modelName = Squad/FX/Monoprop_small', 'transformName = RCSthruster', 'emission = 0.0 0.0', 'emission = 0.1 0.0',
                     'emission = 1.0 1.0', 'speed = 0.0 0.8', 'speed = 1.0 1.0', 'localRotation = -90, 0, 0')))


def command(crew=0, reverse=False):
    r = [block('CONTROLPOINT', 'name = reverse', 'displayName = Reversed Control', 'orientation = 0,180,0')] if reverse else []
    return mod('ModuleCommand', f'minimumCrew = {crew}', 'defaultControlPointDisplayName = Forward', 'hasHibernation = True', *r)


def sas():
    return mod('ModuleSAS', 'SASServiceLevel = 3')


def wheel(t, ec):
    return mod('ModuleReactionWheel', f'PitchTorque = {t}', f'YawTorque = {t}', f'RollTorque = {t}', block('RESOURCE', 'name = ElectricCharge', f'rate = {ec}'))


def antenna(power, kind='INTERNAL'):
    return mod('ModuleDataTransmitter', f'antennaType = {kind}', 'packetInterval = 0.6', 'packetSize = 2', 'packetResourceCost = 12.0', 'requiredResource = ElectricCharge',
               f'antennaPower = {power}', 'antennaCombinable = True')


def part(name, title, desc, tags, mass, cost, cat, tech, extra=(), modules=(), rules='1,1,1,1,0', profiles='size6', crash=20, model=None, node_attach=None, tmax=1700, skin=2700, brk=30000, stackSym=None):
    L = [f'name = {name}', 'module = Part', 'author = lsamman', block('MODEL', f'model = StarshipThingyMabobsAndSuch/ITS/Parts/{model or name}'), 'rescaleFactor = 1', 'scale = 1']
    L += nodes(model or name)
    if node_attach:
        L.append('node_attach = ' + node_attach)
    if stackSym:
        L.append(f'stackSymmetry = {stackSym}')
    L += [f'TechRequired = {tech}', f'entryCost = {cost}', f'cost = {cost}', f'category = {cat}', 'subcategory = 0', f'title = {title}', f'manufacturer = {MFR}',
          f'description = {desc}', f'tags = {tags}' if name.startswith('STMS_') else f'tags = ITS interplanetary starship {tags}', f'attachRules = {rules}', f'mass = {mass}', 'dragModelType = default', 'maximum_drag = 0.2',
          'minimum_drag = 0.2', 'angularDrag = 2', f'crashTolerance = {crash}', f'breakingForce = {brk}', f'breakingTorque = {brk}', f'maxTemp = {tmax}',
          f'skinMaxTemp = {skin}', 'emissiveConstant = 0.85', f'bulkheadProfiles = {profiles}']
    L += list(extra)
    for m in modules:
        L.append(m)
    open(os.path.join(OUT, name + '.cfg'), 'w').write('// Generated by scripts/make_cfg.py; edit there.\n' + '\n'.join(block('PART', *L)) + '\n')


def hide(*names):
    return [f'transform = {n}' for n in names]


def livery(id_, desc, subs):
    """subs: (name, title, colour, [transforms shown]). Transforms not listed by the active subtype are hidden by B9."""
    return mod('ModuleB9PartSwitch', f'moduleID = {id_}', f'switcherDescription = {desc}', 'affectDragCubes = false', 'affectFARVoxels = false',
               *[block('SUBTYPE', f'name = {n}', f'title = {t}', f'primaryColor = {c}', *[f'transform = {x}' for x in tr]) for n, t, c, tr in subs])


def paint(sheet):
    """Hull livery: White (as built, the default) or Bare carbon, which swaps the diffuse of the hull sheet and of the
    details atlas (white trim) for their _carbon versions; normals are shared. Appended last so module indices in saves stay put."""
    tex = lambda t: block('TEXTURE', f'texture = StarshipThingyMabobsAndSuch/ITS/Parts/{t}_carbon_diff', f'currentTexture = {t}_diff')
    return mod('ModuleB9PartSwitch', 'moduleID = ITS_Livery', 'switcherDescription = Livery', 'affectDragCubes = false', 'affectFARVoxels = false',
               block('SUBTYPE', 'name = White', 'title = White', 'primaryColor = #e8e8e8'),
               block('SUBTYPE', 'name = Carbon', 'title = Bare carbon', 'primaryColor = #1a1b1d', tex(sheet), tex('its_det')))


